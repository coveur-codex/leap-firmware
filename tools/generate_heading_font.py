#!/usr/bin/env python3
"""Convert the X11 Helvetica Regular 10 BDF into LEAP's CP437 GFX font.

Source: https://raw.githubusercontent.com/olikraus/u8g2/d6c8499c5f2707cac8eccd09fd8f677d12b17977/tools/font/bdf/helvR10.bdf
Usage: python3 tools/generate_heading_font.py helvR10.bdf LEAP/src/HeadingFont.h
Only ASCII and the additional characters accepted by DisplayText.h are stored.
"""

import argparse
from pathlib import Path


def generate(source: str) -> str:
    glyphs = {}
    for block in source.split("STARTCHAR ")[1:]:
        lines = block.splitlines()
        encoding = int(next(s for s in lines if s.startswith("ENCODING ")).split()[1])
        advance = int(next(s for s in lines if s.startswith("DWIDTH ")).split()[1])
        width, height, dx, dy = map(int, next(s for s in lines if s.startswith("BBX ")).split()[1:])
        rows = lines[lines.index("BITMAP") + 1:lines.index("ENDCHAR")]
        bits = []
        for row in rows:
            value = int(row, 16)
            bits.extend((value >> (len(row) * 4 - 1 - x)) & 1 for x in range(width))
        bitmap = [sum(bit << (7 - j) for j, bit in enumerate(bits[i:i + 8]))
                  for i in range(0, len(bits), 8)]
        glyphs[encoding] = (width, height, advance, dx, -(height + dy), bitmap)

    mapping = {code: code for code in range(32, 127)}
    mapping.update({0x81: 0xfc, 0x82: 0xe9, 0x84: 0xe4, 0x8a: 0xe8,
                    0x8e: 0xc4, 0x94: 0xf6, 0x99: 0xd6, 0x9a: 0xdc,
                    0xe1: 0xdf, 0xf8: 0xb0})
    bitmaps, entries, offsets = [], [], {}
    for code in range(32, 0xf9):
        unicode = mapping.get(code, ord('?'))
        width, height, advance, dx, dy, bitmap = glyphs[unicode]
        if unicode not in offsets:
            offsets[unicode] = len(bitmaps)
            bitmaps.extend(bitmap)
        entries.append(f"  {{{offsets[unicode]}, {width}, {height}, {advance}, {dx}, {dy}}}, // 0x{code:02x}")

    license_lines = source.split("STARTPROPERTIES")[0].splitlines()
    license_text = '\n'.join(line[7:].rstrip() if line.startswith("COMMENT ") else ''
                             for line in license_lines if line.startswith("COMMENT"))
    bitmap_text = '\n'.join('  ' + ', '.join(f'0x{b:02x}' for b in bitmaps[i:i + 16]) + ','
                            for i in range(0, len(bitmaps), 16))
    entry_text = '\n'.join(entries)
    return f'''// Generated by tools/generate_heading_font.py; do not edit bitmap data.
// X11 Helvetica Regular 10 (14px nominal), CP437 subset for DisplayText.h.
// Source: olikraus/u8g2, d6c8499c5f2707cac8eccd09fd8f677d12b17977,
// tools/font/bdf/helvR10.bdf
/*
{license_text}
*/
#pragma once
#include <cstdint>
#include <gfxfont.h>

namespace leap {{
// Plain const arrays reside in flash on ESP32, and also support native tests.
inline const uint8_t HeadingBitmaps[] = {{
{bitmap_text}
}};
inline const GFXglyph HeadingGlyphs[] = {{
{entry_text}
}};
inline const GFXfont HeadingFont = {{
  const_cast<uint8_t *>(HeadingBitmaps), const_cast<GFXglyph *>(HeadingGlyphs),
  32, 0xf8, 18
}};
constexpr int HeadingAscent = 13;
constexpr int HeadingHeight = 16;
constexpr int HeadingLineHeight = 18;
}} // namespace leap
'''


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('bdf', type=Path)
    parser.add_argument('output', type=Path)
    args = parser.parse_args()
    args.output.write_text(generate(args.bdf.read_text()))
