#!/usr/bin/env python3
"""Rasterize Noto Sans at native reading sizes; no scaling or font library on ESP32.

Source (SIL OFL 1.1, see LEAP/src/third_party/noto/OFL.txt):
https://raw.githubusercontent.com/notofonts/noto-fonts/ffebf8c1ee449e544955a7e813c54f9b73848eac/hinted/ttf/NotoSans/NotoSans-Regular.ttf
Usage: python3 tools/generate_reading_font.py NotoSans-Regular.ttf LEAP/src/ReadingFont.h
Generation only: Pillow 12.3.0 / FreeType 2.14.3. Firmware consumes the checked-in header.
"""
import argparse
import hashlib
from pathlib import Path
from PIL import Image, ImageFont

SOURCE_SHA256 = "b85c38ecea8a7cfb39c24e395a4007474fa5a4fc864f6ee33309eb4948d232d5"
CAP_HEIGHTS = (14, 21, 28, 35, 42)  # Match the old range; native hinting may differ by 1 px.
CHARACTERS = {ord(c): c for c in "-ABCDEFGHIJKLMNOPQRSTUVWXYZ"}
CHARACTERS.update({0x8e: "Ä", 0x99: "Ö", 0x9a: "Ü"})  # DisplayText.h / CP437.


def generate(source: Path) -> str:
    if hashlib.sha256(source.read_bytes()).hexdigest() != SOURCE_SHA256:
        raise ValueError("Expected the pinned Noto Sans Regular source font")
    sections, faces, metrics = [], [], []
    for cap in CAP_HEIGHTS:
        size = min(range(8, 80), key=lambda size: (
            abs(ImageFont.truetype(str(source), size).getmask("H", mode="1").size[1] - cap),
            ImageFont.truetype(str(source), size).getmask("H", mode="1").size[1] > cap, size))
        font = ImageFont.truetype(str(source), size)
        bitmap, glyphs = [], {}
        for code, character in CHARACTERS.items():
            mask, (dx, dy) = font.getmask2(character, mode="1", anchor="ls")
            ink = Image.new("L", mask.size)
            ink.putdata(list(mask))
            crop = ink.getbbox()
            assert crop
            ink = ink.crop(crop)
            width, height = ink.size
            offset = len(bitmap)
            bits = [bool(value) for value in ink.tobytes()]
            bitmap.extend(sum(bit << (7 - j) for j, bit in enumerate(bits[i:i + 8]))
                          for i in range(0, len(bits), 8))
            glyphs[code] = (offset, width, height, round(font.getlength(character)),
                            dx + crop[0], dy + crop[1])
        ascent = max(-glyph[5] for glyph in glyphs.values())
        descent = max(glyph[5] + glyph[2] for glyph in glyphs.values())
        lines = [f"inline const uint8_t ReadingBitmap{cap}[] = {{"]
        lines += ["  " + ", ".join(f"0x{value:02x}" for value in bitmap[i:i + 16]) + ","
                  for i in range(0, len(bitmap), 16)]
        lines += ["};", f"inline const GFXglyph ReadingGlyphs{cap}[] = {{"]
        for code in range(45, 0x9b):
            glyph = glyphs.get(code, (0, 0, 0, 0, 0, 0))
            lines.append("  {" + ", ".join(map(str, glyph)) + f"}}, // 0x{code:02x}")
        lines += ["};"]
        sections.append("\n".join(lines))
        faces.append(f"  {{const_cast<uint8_t *>(ReadingBitmap{cap}), "
                     f"const_cast<GFXglyph *>(ReadingGlyphs{cap}), 45, 0x9a, {ascent + descent + 2}}}")
        metrics.append(f"  {{{glyphs[ord('H')][2]}, {ascent}, {ascent + descent}}}")
    return """// Generated by tools/generate_reading_font.py; do not edit bitmap data.
// Noto Sans Regular, native uppercase heights 14/21/28/35/42 px, CP437 subset.
// Copyright 2018 The Noto Project Authors; SIL OFL 1.1: third_party/noto/OFL.txt.
// Source SHA-256: """ + SOURCE_SHA256 + """
#pragma once
#include <cstdint>
#include <gfxfont.h>

namespace leap {
""" + "\n".join(sections) + """
inline const GFXfont ReadingFonts[] = {
""" + ",\n".join(faces) + """
};
struct ReadingFontMetrics { int capHeight, ascent, height; };
inline constexpr ReadingFontMetrics ReadingMetrics[] = {
""" + ",\n".join(metrics) + """
};
} // namespace leap
"""


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("ttf", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    args.output.write_text(generate(args.ttf), encoding="utf-8")
